// A starting repertoire for a player rated roughly 450-800 who keeps losing to
// early attacks on f7.
//
// Two rules shaped every choice here:
//
//   1. ONE FIRST MOVE AS WHITE. 1.e4 against everything, and the four replies
//      that are not 1...e5 are all met the same way: take on d5, take the
//      centre with d4, develop, castle. Five openings, one idea.
//   2. NOTHING THAT HANGS f7 OR NEEDS MEMORISING. No gambits, no sharp main
//      lines, no move-24 novelties. Every line below can be played from
//      understanding after one read.
//
// The list then grew past the seven that rule 1 describes, and rule 1 no longer
// covers the whole file - so here is what replaced it rather than a pretend
// version of it:
//
//   3. SYSTEMS BEFORE LINES. The London, the Colle and the King's Indian
//      Attack as White, the Stonewall and the King's Indian setup as Black:
//      openings where the same moves go on the same squares whatever the
//      opponent does. A system is not better chess than a line. It is less to
//      get wrong under time pressure, which at this level is the same thing.
//   4. EVERY COUNT IN THE PROSE IS CHECKED ON A BOARD. Where an entry says a
//      square is attacked twice and defended once, or that a bishop has one
//      legal move, verify-openings.mjs replays the position and counts. Three
//      sentences written for this file turned out to be false that way - two
//      bishops that were said to be trapped had a square after all, and a
//      knight retreat said to lose a piece loses a pawn.
//
//   5. A BRANCH IS A FULL LINE, NOT A FRAGMENT. Every entry carries
//      `variations`: the places a 500-900 opponent actually leaves the main
//      line - the queen sorties, the Bc4 raid, the gambits, the wrong
//      recapture. Each one is written from move one (`line` shares the first
//      `at` plies with the main line and then diverges) so the verifier can
//      replay it, count on it and evaluate its end the same way it does the
//      main line. A count in a branch is checked exactly like a count in the
//      main line; a branch that ends worse than -1.2 for the student is a
//      failure, not a lesson.
//
